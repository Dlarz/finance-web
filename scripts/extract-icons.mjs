  'local_bar', 'phone_iphone', 'wifi', 'bolt', 'checkroom', 'spa', 'child_care', 'sports_esports',
  'music_note', 'menu_book', 'savings', 'account_balance', 'credit_card', 'local_gas_station',
  'train', 'pedal_bike', 'build', 'cleaning_services', 'celebration', 'redeem', 'volunteer_activism',
  'computer', 'headphones', 'local_pharmacy', 'local_hospital', 'bakery_dining', 'local_pizza',
  'icecream', 'sports_soccer', 'park', 'beach_access', 'hotel', 'luggage', 'local_laundry_service',
