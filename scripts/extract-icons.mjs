  'play_arrow', 'arrow_upward', 'arrow_downward', 'error_outline', 'done', 'language', 'account_balance_wallet',
  'today', 'date_range', 'calendar_month', 'backup', 'refresh', 'system_update', 'add_to_home_screen',
  'keyboard_hide', 'palette', 'more_horiz', 'more_vert', 'filter_list', 'zoom_in', 'north_east', 'south_west',
  'lock', 'verified', 'remove', 'inventory_2', 'wallet', 'pie_chart', 'bar_chart', 'schedule', 'notes',
